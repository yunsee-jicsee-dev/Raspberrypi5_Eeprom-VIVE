FALLBACK = "?"   # 모르는 글자는 이걸로 대신 그린다


class Text:
    """글자를 Surface 로 만들어 주는 작은 폰트.  글리프는 캐시해 둔다."""

    def __init__(self, glyphs=None):
        self.glyphs = GLYPHS if glyphs is None else glyphs
        self._cache = {}

    def char_size(self, scale=1):
        """글자 한 칸의 (가로, 세로) — 가로는 글자 사이 간격을 포함한다."""
        scale = max(1, int(scale))
        return CELL_W * scale, GLYPH_H * scale

    def measure(self, s, scale=1):
        cw, ch = self.char_size(scale)
        return len(s) * cw, ch

    def glyph(self, ch, color, scale=1):
        """글자 한 자. 같은 (글자, 색, 크기) 는 캐시에서 바로 돌려준다."""
        scale = max(1, int(scale))
        color = tuple(color)[:3]
        key = (ch, color, scale)
        img = self._cache.get(key)
        if img is None:
            rows = self.glyphs.get(ch) or self.glyphs.get(FALLBACK) or GLYPHS[" "]
            img = pygame.Surface((CELL_W * scale, GLYPH_H * scale), pygame.SRCALPHA)
            for j, row in enumerate(rows.split("/")):
                for i, dot in enumerate(row):
                    if dot != ".":
                        img.fill(color, (i * scale, j * scale, scale, scale))
            self._cache[key] = img
        return img

    def render(self, s, color, scale=1, shadow=True, shadow_color=(0, 0, 0)):
        """문자열 → 투명 배경 Surface. shadow 면 오른쪽 아래로 1 점 그림자."""
        scale = max(1, int(scale))
        cw, ch = self.char_size(scale)
        off = scale if shadow else 0
        surf = pygame.Surface((max(1, len(s) * cw + off), ch + off), pygame.SRCALPHA)
        if shadow:
            for i, c in enumerate(s):
                surf.blit(self.glyph(c, shadow_color, scale), (i * cw + off, off))
        for i, c in enumerate(s):
            surf.blit(self.glyph(c, color, scale), (i * cw, 0))
        return surf
